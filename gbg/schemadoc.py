"""``gbg schema``: the document Claude reads before writing SQL.

Generated from ``graphdef`` -- the same declarations that create the tables --
so it cannot describe a column that does not exist. Two layers:

* **static** (``docs/SCHEMA.md``, checked by ``--check``): tables, columns,
  relations, ids, macros, and the pitfalls section;
* **live** (``gbg schema`` against a built database): adds row counts and the
  actual values of enum-like columns, which is what stops a query from
  filtering on ``gcase = 'Nominative'`` when the data says ``nominative``.

The pitfalls come first on purpose. Each one is a wrong answer that looks
right -- most of all, reading MACULA's coreference ``subjref`` as the
grammatical subject.
"""

