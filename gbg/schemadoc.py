def _table_md(t: graphdef.Table) -> list[str]:
    lines = [f"### `{t.name}` ({t.kind})", "", t.doc, "",
             "| column | type | null | links to | source | description |",
             "|---|---|---|---|---|---|"]
    for c in t.columns:
        link = f"`{c.ref}` ({c.label})" if c.ref else ""
        null = "" if c.nullable else "no"
        lines.append(f"| `{c.name}` | {c.type} | {null} | {link} | {c.component} | {c.doc} |")
    return lines + [""]


def static_doc() -> str:
    out = ["# Schema: the SBLGNT corpus graph", "",
           "Generated by `gbg schema --write` from `gbg/graphdef.py`. Do not edit by hand.",
           "", "## Read this first", ""]
    out += [f"{i}. {p}" for i, p in enumerate(PITFALLS, 1)]
    out += ["", "## Ids", "",
            "| kind | form | example | cite it? |", "|---|---|---|---|",
            f"| token | `{ids.EDITION}:<xml:id>` | `{ids.EDITION}:n57001001001` | yes |",
            f"| verse | `{ids.EDITION}:<USFM>.<ch>.<v>` | `{ids.EDITION}:PHM.1.20` | yes |",
            f"| book | `{ids.EDITION}:<USFM>` | `{ids.EDITION}:PHM` | yes |",
            "| lemma | `lemma:<NFC lemma>` | `lemma:θεός` | yes (shared across corpora) |",
            f"| sentence | `{ids.EDITION}:s:<leftmost token>` | `{ids.EDITION}:s:n57001001001` | no |",
            f"| word group | `{ids.EDITION}:wg:<leftmost token>.<depth>` | "
            f"`{ids.EDITION}:wg:n57001001001.1` | no |",
            "", "`gbg resolve \"Phlm 10\"` turns a reference into ids; `gbg ref` shows a passage.",
            "", "## Macros (stored in the database)", "",
            "- `gbg_key(s)` -- accent-, breathing-, case- and punctuation-free lookup key.",
            "- `gbg_nfc(s)` -- NFC normalisation (the form every stored string is in).",
            "", "## Tables", ""]
    for t in graphdef.TABLES:
        out += _table_md(t)
    out += ["## Relations", "",
            "Every relation appears in the `edge(src, dst, label, tier, src_table, dst_table)` "
            "view. Under `gbg sql --pgq` the same relations form the property graph "
            f"`{dbmod.PGQ_GRAPH}`, with these labels:", "",
            "| edge-view label | SQL/PGQ label | from | to | defined by |", "|---|---|---|---|---|"]
    for _name, _fill, src, _key, dst, label in dbmod.pgq_edge_tables():
        # An edge table's label is its own name; anything else is a foreign key.
        # (Prefix matching misfiles `lemma_proximity` as a column of `lemma`.)
        edge = graphdef.BY_NAME.get(label)
        if edge is not None and edge.kind == "edge":
            note = " (explicit targets only)" if any(c.name == "implicit"
                                                     for c in edge.columns) else ""
            out.append(f"| {edge.column('dst').label} | `{label}` | `{src}` "
                       f"| `{dst}` | table `{label}`{note} |")
        else:
            t = graphdef.BY_NAME[src]
            col = next(c for c in t.refs if f"{t.name}_{c.label.lower()}" == label)
            out.append(f"| {col.label} | `{label}` | `{src}` | `{dst}` | `{src}.{col.name}` |")
    out.append("| DOMINATES | `dominates` | `wg` | `token` | table `dominance` |")
    out += ["", "Example (`gbg sql --pgq`):", "", "```sql",
            f"FROM GRAPH_TABLE ({dbmod.PGQ_GRAPH}",
            "  MATCH (v:token)-[f:frame_arg]->(a:token)",
            "  WHERE v.lemma = 'ἀγαπάω' AND f.arg_role = 'A0'",
            "  COLUMNS (v.id AS verb, v.ref, a.id AS agent, a.surface))", "```", ""]
    return "\n".join(out)


def _one_line(v, width: int = 60) -> str:
    # Upstream sometimes stores a multi-line annotator note where a value belongs
    # (wg.role, six times); keep the doc readable without hiding that it happens.
    s = " ".join(str(v).split())
    return s if len(s) <= width else s[: width - 1] + "…"


def live_doc(db: Path) -> str:
    con = dbmod.connect(db)
    try:
        build_id, commits = dbmod._meta(con)
        out = ["", "## This build", "",
               f"build `{build_id}`, sources {', '.join(f'{k}@{v[:12]}' for k, v in commits.items())}",
               "", "| table | rows |", "|---|---|"]
        for t in graphdef.TABLES:
            n = con.execute(f'SELECT count(*) FROM "{t.name}"').fetchone()[0]
            out.append(f"| `{t.name}` | {n} |")
        out += ["", "### Values of enum-like columns", ""]
        for t in graphdef.TABLES:
            for c in t.columns:
                if not c.enum:
                    continue
                vals = con.execute(f'SELECT "{c.name}", count(*) FROM "{t.name}" GROUP BY 1 '
                                   f"ORDER BY 2 DESC, 1 LIMIT 25").fetchall()
                shown = ", ".join(("NULL" if v is None else f"`{_one_line(v)}`") + f" ({n})"
                                  for v, n in vals)
                out.append(f"- `{t.name}.{c.name}`: {shown}")
        return "\n".join(out) + "\n"
    finally:
        con.close()


def add_arguments(p) -> None:
    cli.add_db(p)
    mode = p.add_mutually_exclusive_group()
    mode.add_argument("--static", action="store_true", help="structure only (no database)")
    mode.add_argument("--write", action="store_true", help="write docs/SCHEMA.md")
    mode.add_argument("--check", action="store_true",
                      help="exit 2 if docs/SCHEMA.md differs from what graphdef generates")


def run(args) -> int:
    root = cli.root_of(args)
    target = root / "docs" / "SCHEMA.md"
    doc = static_doc()
    if args.write:
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text(doc, encoding="utf-8")
        print(f"wrote {target}")
        return cli.EXIT_OK
    if args.check:
        if target.is_file() and target.read_text(encoding="utf-8") == doc:
            print("schema --check: docs/SCHEMA.md matches graphdef")
            return cli.EXIT_OK
        print("schema --check: docs/SCHEMA.md is stale; regenerate with `gbg schema --write`",
              file=sys.stderr)
        return cli.EXIT_USAGE
    print(doc, end="")
    db = cli.db_of(args)
    if not args.static and db.is_file():
        print(live_doc(db), end="")
    return cli.EXIT_OK
